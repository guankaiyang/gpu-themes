const glyphCover = (g: number, dx: number, dy: number): number =>
  atlas.sample(vec2((g * 18 + clamp((dx + 4.5) * 2, 0.5, 17.5)) / 126, clamp((dy + 10.5) * 2, 0.5, 25.5) / 26)).r

// The share of cells along an edge that glow, and their group: tealEdge()'s pick, at a facing cell.
const tealPick = (x: number, y: number, seed: number): number =>
  hashOf(quotOf(x, 2) + seed, quotOf(y, 2) * 3) * 0.7 + hashOf(x + seed, y) * 0.3

// One corner of a two-triangle quad.
