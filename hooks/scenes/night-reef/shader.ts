const pick6 = (l: readonly number[], i: number): number =>
  i < 0.5 ? l[0]! : i < 1.5 ? l[1]! : i < 2.5 ? l[2]! : i < 3.5 ? l[3]! : i < 4.5 ? l[4]! : l[5]!

// Turn a cell of a map drawn heading up to face `heading` (0 up, 1 down, 2 left, 3 right), as facing() does.
const faceOf = (x: number, y: number, heading: number, height: number): vec2 =>
  heading < 0.5 ? vec2(x, y) : heading < 1.5 ? vec2(x, height - 1 - y) : heading < 2.5 ? vec2(y, x) : vec2(height - 1 - y, x)

// One tile of an animal. Instances run through the cells four times, once for each leg, in the order the legs are drawn.
const tileCorner = (v: number, i: number, animal: number) => {
  const rows = animal < 0.5 ? RAY_ROWS : TURTLE_ROWS
  const leg = quotOf(i, rows)
  const code = int(animal < 0.5 ? signed(RAY.at(i - leg * rows)) : signed(TURTLE.at(i - leg * rows)))
  const x = animal < 0.5 ? unsigned(code & 15) : unsigned(code & 31)
  const y = animal < 0.5 ? unsigned((code >>> 4) & 15) : unsigned((code >>> 5) & 15)
  const local = animal < 0.5 ? unsigned((code >>> 8) & 7) : unsigned((code >>> 9) & 15)
  const set = animal < 0.5 ? unsigned((code >>> 11) & 1) : unsigned((code >>> 13) & 7)
  const edge = animal < 0.5 ? unsigned((code >>> 12) & 1) : 0
  const kind = animal < 0.5 ? local + 9 : local
  const full = leg < 0.5 || (leg > 1.5 && leg < 2.5) ? 1 : 0
  // The turtle's legs head down, left, up, right; the ray's up, right, down, left.
  const heading = animal < 0.5
    ? (leg < 0.5 ? 0 : leg < 1.5 ? 3 : leg < 2.5 ? 1 : 2)
    : (leg < 0.5 ? 1 : leg < 1.5 ? 2 : leg < 2.5 ? 0 : 3)
  const cell = faceOf(x, y, heading, animal < 0.5 ? 14 : 15)
  // The short turns sit a little off the lap: the turtle's by (40, -40), the ray's by (-10, 10).
  const shortShift = animal < 0.5 ? vec2(-10, 10) : vec2(40, -40)
  const at = vec2(lapAt(animal) + shortShift * (1 - full) + cell * 20)
  // Which pose shows: the turtle's three strokes in the order 0 1 2 1 over 7 s, the ray's two over 9 s (30 s in).
  const q3 = fract(time / 7)
  const pa = 1 - ramp(q3, 0.2, 0.25) + ramp(q3, 0.95, 1)
  const pb = ramp(q3, 0.2, 0.25) - ramp(q3, 0.45, 0.5) + ramp(q3, 0.7, 0.75) - ramp(q3, 0.95, 1)
  const pc = ramp(q3, 0.45, 0.5) - ramp(q3, 0.7, 0.75)
  const q2 = fract((time + 30) / 9)
  const first = 1 - ramp(q2, 0.45, 0.5) + ramp(q2, 0.95, 1)
  const turtlePose = set < 0.5 ? 1 : full > 0.5 ? (set < 2.5 ? pa : set < 4.5 ? pb : pc) : set > 2.5 && set < 4.5 ? 1 : 0
  const rayPose = full > 0.5 ? (set < 0.5 ? first : 1 - first) : set < 0.5 ? 1 : 0
  const opacity = local > 4.5 ? 0.25 : local > 3.5 ? 0.45 : local > 2.5 ? 0.7 : 1
  const shown = legOf(leg, lapOf(animal)) * (animal < 0.5 ? rayPose * opacity : turtlePose)
  // The glow on the full legs: the turtle's scutes (inner and outer) and spine, and part of its shell's rim in six
  // groups; part of the ray's edge in two.
  const pick = tealPick(cell.x, cell.y, animal < 0.5 ? 70 : 0)
  const turtleGlow = local > 4.5 && local < 5.5
    ? (abs(cell.x - 9) + abs(cell.y - 9) <= 1 ? INNER_EMBER : OUTER_EMBER)
    : local > 5.5 && local < 6.5
      ? SPINE_EMBER
      : local > 2.5 && local < 3.5 && pick < 0.7
        ? TURTLE_RIM + floor((pick / 0.7) * 6)
        : -1
  const rayGlow = edge > 0.5 && pick < 0.9 ? RAY_RIM + floor((pick / 0.9) * 2) : -1
  const glow = full > 0.5 ? (animal < 0.5 ? rayGlow : turtleGlow) : -1
  const glowRow = animal < 0.5 ? TEAL_ROW : local > 4.5 && local < 5.5 ? VIOLET_ROW : local > 5.5 && local < 6.5 ? WARM_ROW : TEAL_ROW
  const cx = pick6(QX, v) * 20
  const cy = pick6(QY, v) * 20
  return {
    at: clipOf(vec2(at.x + cx, at.y + cy)),
    a: vec4(cx, cy, kind, glyphIndex(cell.x, cell.y)),
    b: vec4(shown, glow, glowRow, 0),
    hide: shown < 0.002,
  }
}

// A cell's tile as the mosaic draws it: an 18-unit tile with a faint edge, its glyph, then a glowing group over it.
const tilePaint = (s: Spot): vec4 => {
  const w = s.px / scaleOf()
  const lx = s.a.x
  const ly = s.a.y
  const kind = floor(s.a.z + 0.5)
  const fill = cover(1, 19, lx, w) * cover(1, 19, ly, w)
  const outer = cover(0.5, 19.5, lx, w) * cover(0.5, 19.5, ly, w)
  const inner = cover(1.5, 18.5, lx, w) * cover(1.5, 18.5, ly, w)
  const edge = (outer - inner) * 0.06
  const g = glyphCover(floor(s.a.w + 0.5), lx - 10, ly - 15)
  let acc = vec4(colorOf(kind * 2) * fill, fill)
  acc = vec4(EDGE * edge + acc.rgb * (1 - edge), edge + acc.a * (1 - edge))
  acc = vec4(colorOf(kind * 2 + 1) * g + acc.rgb * (1 - g), g + acc.a * (1 - g))
  const glow = floor(s.b.y + 0.5)
  const row = floor(s.b.z + 0.5)
  const o = glow > -0.5 ? clockOf(max(glow, 0)) : 0
  const lit = vec3(mix(colorOf(row * 2), colorOf(row * 2 + 1), g))
  const ga = o * max(fill, g)
  acc = vec4(lit * ga + acc.rgb * (1 - ga), ga + acc.a * (1 - ga))
  return vec4(acc * s.b.x)
}

// The swarms and the middle specks, onto their own layer, which the reef's tiles cover. Each swarm's instances run
// through its specks six times, once for each of its layers in the order they are drawn: three teal paths, the violet
// one, the halos, the bright ones. The middle specks come last.
const low = buffer({ filter: 'nearest' })
const lowSpecks = shapes(
  { count: 6, instances: 978, cover: 0.2, draw: 'triangles', into: low, clear: true },
  (v, i) => {
    const k = i < 288 ? 0 : i < 504 ? 1 : i < 684 ? 2 : i < 960 ? 3 : 4
    const start = k < 0.5 ? 0 : k < 1.5 ? 288 : k < 2.5 ? 504 : k < 3.5 ? 684 : 960
    const sw = SWARMS.at(min(k, 3) * 2)
    const sw2 = SWARMS.at(min(k, 3) * 2 + 1)
    const count = k < 3.5 ? signed(sw2[0]) : 18
    const j = i - start
    const layer = k < 3.5 ? quotOf(j, count) : 6
    const n = remOf(j, count)
    const seed = signed(sw2[1])
    // swarm(): where the speck lies, and what it is.
    const angle = hashOf(seed, n * 2) * PI * 2
    const reach = pow(hashOf(seed, n * 2 + 1), 0.8)
    const sx = roundOf(signed(sw[0]) + cos(angle) * signed(sw[2]) * reach)
    const sy = roundOf(signed(sw[1]) + sin(angle) * signed(sw[3]) * reach)
    const roll = hashOf(seed + 7, n)
    const part = remOf(n, 3)
    const mine = layer < 2.5 ? (roll >= 0.36 && part === layer ? 1 : 0) : layer < 3.5 ? (roll >= 0.1 && roll < 0.36 ? 1 : 0) : layer < 5.5 ? (roll < 0.1 ? 1 : 0) : 1
    const side = layer < 2.5 ? (roll < 0.6 ? 3 : roll < 0.85 ? 2 : 1.5) : layer < 3.5 ? 3 : layer < 4.5 ? 0 : layer < 5.5 ? 4 : 1.5
    // middleScatter(): the faint specks through the reading column.
    const x = layer > 5.5 ? roundOf(470 + hashOf(51, n) * 700) : layer > 3.5 && layer < 4.5 ? sx + 2 : sx
    const y = layer > 5.5 ? roundOf(60 + hashOf(52, n) * 860) : layer > 3.5 && layer < 4.5 ? sy + 2 : sy
    const drift = k < 3.5 ? vec2(vec2(signed(sw2[2]), signed(sw2[3])) * clockOf(k * 6 + 5)) : vec2(0, 0)
    const clock = k < 3.5 ? k * 6 + min(layer, 4) : SCATTER_CLOCK
    // A halo's quad is its circle's box about its centre; a speck's runs from its corner, with a unit to spare.
    const halo = layer > 3.5 && layer < 4.5 ? 1 : 0
    const from = halo > 0.5 ? -11 : -1
    const span = halo > 0.5 ? 22 : side + 2
    const lx = from + pick6(QX, v) * span
    const ly = from + pick6(QY, v) * span
    return {
      at: clipOf(vec2(vec2(x, y) + drift + vec2(lx, ly))),
      a: vec4(lx, ly, side, layer),
      b: vec4(clockOf(clock), 0, 0, 0),
      hide: mine < 0.5,
    }
  },
  s => {
    const w = s.px / scaleOf()
    const layer = floor(s.a.w + 0.5)
    const o = s.b.x
    const c = cover(0, s.a.z, s.a.x, w) * cover(0, s.a.z, s.a.y, w)
    const t = length(vec2(s.a.x, s.a.y)) / 11
    const haloAlpha = (t < 0.4 ? mix(0.5, 0.14, t / 0.4) : t < 1 ? mix(0.14, 0, (t - 0.4) / 0.6) : 0) * o
    // A middle speck is in the still at 0.3 x 0.28; lay on only what makes it 0.3 x o.
    const held = 0.3 * 0.28
    const topUp = (c * (0.3 * o - held)) / (1 - c * held)
    const alpha = layer < 3.5 || (layer > 4.5 && layer < 5.5) ? c * o : layer < 4.5 ? haloAlpha : topUp
    const color = layer < 2.5 ? TEAL : layer < 3.5 ? SOFT_VIOLET : layer < 4.5 ? TEAL : layer < 5.5 ? BRIGHT : TEAL
    return vec4(color * alpha, alpha)
  },
)

// The moonlight bands, which slide 90 units each way, skewed 28 degrees: a linear ramp up to 0.085 and down.
const moonlight = (vb: vec2): number => {
  const gx = vb.x + 0.5317094316614788 * vb.y
  const ua = (gx - 170 - (-90 + 180 * clockOf(CAUSTIC_A))) / 280
  const ub = (gx - 1420 - (-90 + 180 * clockOf(CAUSTIC_B))) / 320
  return 0.085 * (max(1 - abs(2 * ua - 1), 0) + max(1 - abs(2 * ub - 1), 0))
}
const deepAlpha = (t: number): number =>
  t < 0.35 ? mix(0.6, 0.34, t / 0.35) : t < 0.7 ? mix(0.34, 0.1, (t - 0.35) / 0.35) : t < 1 ? mix(0.1, 0, (t - 0.7) / 0.3) : 0
const tealGlow = (t: number): number =>
  t < 0.25 ? mix(0.24, 0.15, t / 0.25) : t < 0.5 ? mix(0.15, 0.07, (t - 0.25) / 0.25) : t < 0.75 ? mix(0.07, 0.02, (t - 0.5) / 0.25) : t < 1 ? mix(0.02, 0, (t - 0.75) / 0.25) : 0
const violetGlow = (t: number): number =>
  t < 0.3 ? mix(0.2, 0.11, t / 0.3) : t < 0.6 ? mix(0.11, 0.04, (t - 0.3) / 0.3) : t < 1 ? mix(0.04, 0, (t - 0.6) / 0.4) : 0
const over = (acc: vec4, color: vec3, a: number): vec4 => vec4(color * a + acc.rgb * (1 - a), a + acc.a * (1 - a))

// Under the animals: the moonlight, the swarms, the reef's breathing tiles, then the halos.
// gpu-themes: the scene fades in when its shader starts, so its moving parts do not pop in over the still. The app
// crossfades from the old backdrop to this one's still; the shader then rises over the still in FADE_IN seconds,
// after FADE_WAIT. A one-texel clock notes the first frame, whatever time the app starts the shader's clock at.
const FADE_WAIT = 0.15
const FADE_IN = 0.8
// x: how much of the scene is still hidden, 1 to 0. y: the time the fade starts from. w: 1 once noted.
const fadeClock: Buffer = buffer({ size: [1, 1], float: 32, filter: 'nearest' }, () => {
  const last = fadeClock.at(vec2(0, 0))
  // Frame 0 starts the fade; a clock wiped later (the app may clear buffers) counts as long risen, with no replay.
  const startAt = last.w > 0.5 ? last.y : first ? time : time - FADE_WAIT - FADE_IN - 1
  return vec4(1 - smoothstep(startAt + FADE_WAIT, startAt + FADE_WAIT + FADE_IN, time), startAt, 0, 1)
})
// The picture or a shape over it, as far as the scene has risen: until then the still shows through.
function fadingIn(c: vec4): vec4 {
  return vec4(c * (1 - fadeClock.at(vec2(0, 0)).x))
}

function viewColor(p: Pixel) {
  const s = scaleOf()
  const vb = vbOf(p.point, s, originOf(s))
  const w = px / s
  const cell = floor(vec2(vb / 20))
  const local = vec2(vb - cell * 20)
  const inside = cell.x >= 0 && cell.x < 80 && cell.y >= 0 && cell.y < 50 ? 1 : 0
  const m = vec4(mask.at(cell) * inside)
  const fill = cover(1, 19, local.x, w) * cover(1, 19, local.y, w)
  const solid = m.r * fill

  // The moonlight lies under the deep water's glow: laid over it here, it takes the glow's colour where the glow is.
  const c = moonlight(vb) * (1 - solid)
  const deep = deepAlpha(length(vec2((vb.x - 1640) / 900, (vb.y - 1040) / 640)))
  let acc = vec4(vec3(mix(MOONLIGHT, DEEP, deep)) * c, c)

  const l = vec4(low.sample(p.uv) * (1 - solid))
  acc = vec4(l.rgb + acc.rgb * (1 - l.a), l.a + acc.a * (1 - l.a))

  // The reef's anemones and amber tips: the still has them at their dimmest; lay on what brings them to the clock's
  // value. Where a tip lies on an anemone, both are brought up together.
  const g = glyphCover(glyphIndex(cell.x, cell.y), local.x - 10, local.y - 15)
  const s1 = m.g * fill * 0.14
  const o1 = m.g * fill * clockOf(ANEMONE)
  const s2 = m.b * fill * 0.35
  const o2 = m.b * fill * clockOf(TIP)
  const keep = ((1 - o2) * (1 - o1)) / max((1 - s2) * (1 - s1), 0.0001)
  const anColor = vec3(mix(TEAL, TEAL_INK, g))
  const tpColor = vec3(mix(WARM, WARM_INK, g))
  const lay = vec3(tpColor * max(o2 - keep * s2, 0) + anColor * max((1 - o2) * o1 - keep * (1 - s2) * s1, 0))
  acc = vec4(lay + acc.rgb * keep, 1 - keep + acc.a * keep)

  // The halos: the ray's, then the turtle's teal and violet.
  const ray = lapAt(0)
  const turtle = lapAt(1)
  const h1 = tealGlow(length(vec2((vb.x - ray.x - 130) / 280, (vb.y - ray.y - 110) / 240))) * clockOf(RAY_HALO)
  acc = over(acc, TEAL, h1)
  const h2 = tealGlow(length(vec2((vb.x - turtle.x - 190) / 300, (vb.y - turtle.y - 160) / 300))) * clockOf(TURTLE_HALO)
  acc = over(acc, TEAL, h2)
  const h3 = violetGlow(length(vec2((vb.x - turtle.x - 190) / 170, (vb.y - turtle.y - 150) / 180))) * clockOf(TURTLE_VIOLET_HALO)
  acc = over(acc, VIOLET, h3)
  return vec4(acc * (1 + params.variant * 0))
}
const view = picture(p => fadingIn(viewColor(p)))

// Covers: the most a draw shows at once at the largest scale (a 7680 x 2160 window, 4.8 points a unit), with a little
// to spare: 13 halos and 160 specks (0.16 windows); two legs of wake (0.10); the ray's two poses and a turn (174
// tiles, 1.12); the turtle's body twice and three stroke phases (252 tiles, 1.63).
// Over the halos, straight onto the picture: each animal's ripples and its two wakes (three bands each), the ray's
// first. Instances: the ray's 12 ripples and 2 x 3 x 36 wake specks, then the turtle's 16 and 2 x 3 x 66.
const animSpecksPaint = (s: Spot): vec4 => {
    const w = s.px / scaleOf()
    const a = cover(0, s.a.z, s.a.x, w) * cover(0, s.a.w, s.a.y, w) * s.b.x
    return vec4(vec3(s.b.y > 0.5 ? RIPPLE : TEAL) * a, a)
  }
const animSpecks = shapes(
  { count: 6, instances: 640, cover: 0.12, draw: 'triangles' },
  (v, i) => {
    const owner = i < 228 ? 0 : 1
    const j = i - owner * 228
    const ripples = owner < 0.5 ? 12 : 16
    const n = owner < 0.5 ? 36 : 66
    const ripple = j < ripples ? 1 : 0
    // nearRipples(): a dash on the 20-unit grid near the animal.
    const rw = owner < 0.5 ? 260 : 380
    const rh = owner < 0.5 ? 180 : 300
    const rseed = owner < 0.5 ? 811 : 801
    const rx = roundOf((-90 + hashOf(rseed, j) * (rw + 180)) / 20) * 20 + 6
    const ry = roundOf((-70 + hashOf(rseed + 1, j) * (rh + 140)) / 20) * 20 + 9
    // wake(): plankton stirred up behind it, for the leg heading up or down.
    const k = j - ripples
    const which = quotOf(k, 3 * n)
    const kk = k - which * 3 * n
    const band = quotOf(kk, n)
    const m = kk - band * n
    const wc = owner < 0.5 ? 13 : 19
    const hc = owner < 0.5 ? 14 : 15
    const lc = owner < 0.5 ? 6 : 11
    const wseed = owner < 0.5 ? 600 : 500
    const along = pow(hashOf(wseed, m), 1.4)
    const spread = (0.2 + along * 0.4) * wc * 20
    const wx = roundOf((wc * 20) / 2 + (hashOf(wseed + 1, m) - 0.5) * spread)
    const py = roundOf(hc * 20 - 30 + along * lc * 20)
    const down = owner < 0.5 ? which > 0.5 : which < 0.5
    const wy = down ? hc * 20 - py : py
    const wsize = hashOf(wseed + 2, m) < 0.3 ? 3 : 2
    const mine = ripple > 0.5 || min(2, floor(along * 3)) === band ? 1 : 0
    const wd = ripple > 0.5 ? 8 : wsize
    const h = ripple > 0.5 ? 2 : wsize
    const leg = which * 2
    const fo = ripple > 0.5 ? 0.4 : band < 0.5 ? 0.85 : band < 1.5 ? 0.55 : 0.3
    const clock = ripple > 0.5 ? RIPPLE_CLOCK : WAKE_CLOCK + band
    const shown = (ripple > 0.5 ? 1 : legOf(leg, lapOf(owner))) * clockOf(clock) * fo * mine
    const lx = -1 + pick6(QX, v) * (wd + 2)
    const ly = -1 + pick6(QY, v) * (h + 2)
    const x = ripple > 0.5 ? rx : wx
    const y = ripple > 0.5 ? ry : wy
    return {
      at: clipOf(vec2(lapAt(owner) + vec2(x + lx, y + ly))),
      a: vec4(lx, ly, wd, h),
      b: vec4(shown, ripple, 0, 0),
      hide: shown < 0.002,
    }
  },
  spot => fadingIn(animSpecksPaint(spot)),
)
