// Per cell of the lagoon, drawn once. r: the opacity of the island's or shoal's tile there; g: which dimming tile it
// is, plus one, or 64 plus the sparkle near it, / 255; b: a deep patch (sampled smoothly for its edges); a: a cell the
// animals rest on in the still.
const ground = buffer({ size: [COLUMNS, ROWS], once: true, filter: 'linear' }, p => {
  const x = p.cell.x
  const y = p.cell.y
  let kind = 0
  for (const n of range(85)) {
    const r = int(STATIC.at(n))
    const on = abs(y - unsigned(r & 127)) < 0.5 && x > unsigned((r >>> 7) & 127) - 0.5 && x < unsigned((r >>> 14) & 127) + 0.5
    kind = on ? unsigned((r >>> 21) & 7) : kind
  }
  const opacity = kind < 0.5 ? 0 : kind < 1.5 ? 1 : kind < 2.5 ? 0.95 : kind < 3.5 ? 0.9 : kind < 4.5 ? 0.75 : 0.6
  // patches(): each row of a patch is inset by a rounded amount from both sides.
  let patch = 0
  for (const n of range(5)) {
    const q = PATCHES.at(n)
    const row = y - q.y
    const inset = floor(abs(row - q.w / 2) * 0.9 + (hashOf(q.x + row, q.y) - 0.5) * 3 + 0.5)
    const from = q.x + inset
    const on = row > -0.5 && row < q.w - 0.5 && x > from - 0.5 && x < from + max(2, q.z - inset * 2) - 0.5
    patch = on ? 1 : patch
  }
  let erase = 0
  for (const n of range(39)) {
    const r = int(ERASE.at(n))
    const on = abs(y - unsigned(r & 127)) < 0.5 && x > unsigned((r >>> 7) & 127) - 0.5 && x < unsigned((r >>> 14) & 127) + 0.5
    erase = on ? 1 : erase
  }
  let dim = 0
  for (const n of range(21)) {
    const r = int(DIMS.at(n))
    dim = abs(x - unsigned(r & 127)) < 0.5 && abs(y - unsigned((r >>> 7) & 127)) < 0.5 ? n + 1 : dim
  }
  // The cells each sparkle touches, its radius and a unit of smoothing out from its centre (none share a cell).
  for (const n of range(9)) {
    const sp = SPARKS.at(n)
    const reach = sp.z / 10 + 1
    const near = x > floor((sp.x - reach) / CELL) - 0.5 && x < floor((sp.x + reach) / CELL) + 0.5 &&
      y > floor((sp.y - reach) / CELL) - 0.5 && y < floor((sp.y + reach) / CELL) + 0.5
    dim = near ? 64 + n : dim
  }
  return vec4(opacity, dim / 255, patch, erase)
})

const over = (top: vec4, below: vec4): vec4 => vec4(top + below * (1 - top.a))
// How much of a pixel `w` wide at `x` lies in [lo, hi].
const box = (x: number, lo: number, hi: number, w: number): number =>
  clamp((min(x + w * 0.5, hi) - max(x - w * 0.5, lo)) / w, 0, 1)
const box2 = (q: vec2, lo: number, hi: number, w: number): number => box(q.x, lo, hi, w) * box(q.y, lo, hi, w)
// Where to sample a stepped map, in cells, so that each cell edge blends over one pixel (`w` cells), as a path does.
const seamOf = (pc: vec2, w: number): vec2 => {
  const seam = floor(vec2(pc + 0.5))
  return vec2(seam + clamp(vec2((pc - seam) / w), -0.5, 0.5))
}

// The bare water of the still where nothing stands on it: the gradient, the glow, the patches, the sun and the grid.
const waterAt = (vb: vec2, u: number): vec3 => {
  const t = clamp((vb.x / 1600 + (vb.y / 1000) * 0.03) / 1.0009, 0, 1)
  let c = WATER.at(0).yzw
  for (const n of range(9)) {
    const a = WATER.at(n)
    const b = WATER.at(n + 1)
    c = t >= a.x ? vec3(mix(a.yzw, b.yzw, clamp((t - a.x) / (b.x - a.x), 0, 1))) : c
  }
  const g = length(vec2((vb.x - 576) / 448, (vb.y - 400) / 420))
  const glow = g < 0.35 ? mix(0.28, 0.18, g / 0.35) : g < 0.7 ? mix(0.18, 0.06, (g - 0.35) / 0.35) : g < 1 ? mix(0.06, 0, (g - 0.7) / 0.3) : 0
  c = vec3(mix(c, GLOW, glow))
  const pc = seamOf(vec2(vb / CELL), u / CELL)
  const patch = ground.sample(vec2(pc / vec2(COLUMNS, ROWS))).b * 0.075
  c = vec3(mix(c, PATCH, patch))
  const sd = length(vec2((vb.x - 1600) / 560, vb.y / 460))
  const sun =
    sd < 0.2 ? mix(0.8, 0.58, sd / 0.2)
      : sd < 0.4 ? mix(0.58, 0.36, (sd - 0.2) / 0.2)
        : sd < 0.6 ? mix(0.36, 0.18, (sd - 0.4) / 0.2)
          : sd < 0.8 ? mix(0.18, 0.06, (sd - 0.6) / 0.2)
            : sd < 1 ? mix(0.06, 0, (sd - 0.8) / 0.2) : 0
  c = vec3(mix(c, SUN, sun))
  const lx = mod(vb.x, CELL)
  const ly = mod(vb.y, CELL)
  const cx = box(lx, 0, 1, u) + box(lx, CELL, CELL + 1, u)
  const cy = box(ly, 0, 1, u) + box(ly, CELL, CELL + 1, u)
  const east = clamp((vb.x / 1600 - 0.64) / 0.18, 0, 1)
  return vec3(mix(c, LINE, 0.08 * east * (cx + cy - cx * cy)))
}

// One glint ellipse's soft mask at a point of the drifting field.
const glintOf = (q: vec2, cx: number, cy: number, rx: number, ry: number): number => {
  const e = length(vec2((q.x - cx) / rx, (q.y - cy) / ry))
  return e < 0.3 ? mix(1, 0.7, e / 0.3) : e < 0.65 ? mix(0.7, 0.22, (e - 0.3) / 0.35) : e < 1 ? mix(0.22, 0, (e - 0.65) / 0.35) : 0
}

// How much of glyph `g` covers a point (dx, dy) view-box units from its centre and baseline.
const glyphCover = (g: number, dx: number, dy: number): number => {
  const tx = (dx + 3.5) * 2
  const ty = (dy + 9) * 2
  const ink = atlas.sample(vec2((g * 15 + clamp(tx, 0.5, 13.5)) / 105, clamp(ty, 0.5, 21.5) / 22)).r
  return tx > 0 && tx < 14 && ty > 0 && ty < 22 ? ink : 0
}

// The shadow's or underside's cover of map `sub` at `pc` (cells), each cell edge blended over one pixel.
const shapeCover = (sub: number, pc: vec2, w: number): vec2 => {
  const q = seamOf(pc, w)
  const tx = clamp(q.x + 10, 0.5, SUB_W - 0.5) + sub * SUB_W
  const ty = clamp(q.y + 8, 0.5, SUB_H - 0.5)
  return cells.sample(vec2(tx / (SUB_W * 5), ty / SUB_H)).ba
}

// One animal of map `sub` at `l` view-box units from its translate: its shadow `off` units right and down, its
// underside 2 units down, then its tiles with their pale edges and glyphs. Premultiplied.
const animalAt = (sub: number, l: vec2, off: number, shadowOpacity: number, u: number): vec4 => {
  const w = u / CELL
  const sh = shapeCover(sub, vec2((l - off) / CELL), w).x * shadowOpacity
  const ud = shapeCover(sub, vec2((l - vec2(0, 2)) / CELL), w).y * 0.5
  let acc = vec4(SHADOW * sh, sh)
  acc = over(vec4(UNDERSIDE * ud, ud), acc)
  const c = floor(vec2(l / CELL))
  const t = cells.at(vec2(clamp(c.x + 10, 0, SUB_W - 1) + sub * SUB_W, clamp(c.y + 8, 0, SUB_H - 1)))
  const code = floor(t.r * 255 + 0.5)
  if (code > 0.5) {
    const q = vec2(l - c * CELL)
    const fill = box2(q, 1, 14, u)
    const edge = box2(q, 0.5, 14.5, u) - box2(q, 1.5, 13.5, u)
    let tile = vec4(KINDS.at(code) * fill, fill)
    tile = over(vec4(vec3(0.24 * edge), 0.24 * edge), tile)
    const ink = glyphCover(floor(t.g * 255 + 0.5), q.x - 7.5, q.y - 11)
    tile = over(vec4(KINDS.at(code + 11) * ink, ink), tile)
    // The 'c' tiles' group is drawn at 0.95.
    acc = over(vec4(tile * (code > 9.5 ? 0.95 : 1)), acc)
  }
  return acc
}

// Both animals, drawn once at two texels a unit: the turtle's four poses in a 2 x 2 block, each covering x -136..212
// and y -106..214 from its translate, then the coral animal over x and y -46..108.
const POSE_W = 696
const POSE_H = 640
const CORAL_W = 308
const poses = buffer({ size: [POSE_W * 2 + CORAL_W, POSE_H * 2], once: true, filter: 'mipmap' }, p => {
  const isCoral = p.cell.x > POSE_W * 2 - 0.5
  const col = isCoral ? 0 : floor(p.cell.x / POSE_W)
  const row = floor(p.cell.y / POSE_H)
  const origin = isCoral ? vec2(POSE_W * 2, 0) : vec2(col * POSE_W, row * POSE_H)
  const l = vec2((p.cell - origin + 0.5) / 2 + (isCoral ? vec2(-46, -46) : vec2(-136, -106)))
  const look = isCoral ? animalAt(4, l, 30, 0.2, 0.5) : animalAt(col + row * 2, l, 45, 0.38, 0.5)
  return isCoral && p.cell.y > CORAL_W - 0.5 ? vec4(0) : look
})
// One pose (0 to 3, or 4 for the coral animal) at `l` units from its translate, sampled smoothly; nothing outside.
const poseAt = (sub: number, l: vec2): vec4 => {
  const isCoral = sub > 3.5
  const origin = isCoral ? vec2(POSE_W * 2, 0) : vec2(mod(sub, 2) * POSE_W, floor(sub / 2) * POSE_H)
  const extent = isCoral ? vec2(CORAL_W, CORAL_W) : vec2(POSE_W, POSE_H)
  const t = vec2((l - (isCoral ? vec2(-46, -46) : vec2(-136, -106))) * 2)
  const inside = t.x > 0 && t.y > 0 && t.x < extent.x && t.y < extent.y ? 1 : 0
  const at = vec2(origin + clamp(t, vec2(0.5), vec2(extent - 0.5)))
  return vec4(poses.sample(vec2(at / vec2(POSE_W * 2 + CORAL_W, POSE_H * 2))) * inside)
}

// The bare water over the cells the animals rest on, drawn once at two texels a unit: the turtle's block (x 1245,
// y 360, 345 units square) and the coral animal's (x 90, y 390, 180 square), side by side.
const rest = buffer({ size: [1050, 690], once: true, filter: 'linear' }, p => {
  const isCoral = p.cell.x > 689.5
  const vb = vec2((p.cell - (isCoral ? vec2(690, 0) : vec2(0)) + 0.5) / 2 + (isCoral ? vec2(90, 390) : vec2(1245, 360)))
  const erased = ground.at(floor(vec2(vb / CELL))).a > 0.5 && !(isCoral && p.cell.y > 359.5)
  return erased ? vec4(waterAt(vb, 0.5), 1) : vec4(0)
})
const restAt = (vb: vec2): vec4 => {
  const isCoral = vb.x < 800
  const t = vec2((vb - (isCoral ? vec2(90, 390) : vec2(1245, 360))) * 2)
  const extent = isCoral ? 360 : 690
  const at = vec2(clamp(t, vec2(0.5), vec2(extent - 0.5)) + (isCoral ? vec2(690, 0) : vec2(0)))
  return rest.sample(vec2(at / vec2(1050, 690)))
}

// gpu-themes: the scene fades in when its shader starts, so its moving parts do not pop in over the still. The app
// crossfades from the old backdrop to this one's still; the shader then rises over the still in FADE_IN seconds,
// after FADE_WAIT. A one-texel clock notes the first frame, whatever time the app starts the shader's clock at.
const FADE_WAIT = 0.15
const FADE_IN = 0.8
// x: how much of the scene is still hidden, 1 to 0. y: the time the fade starts from. w: 1 once noted.
const fadeClock: Buffer = buffer({ size: [1, 1], float: 32, filter: 'nearest' }, () => {
  const last = fadeClock.at(vec2(0, 0))
  // Frame 0 starts the fade; a clock wiped later (the app may clear buffers) counts as long risen, with no replay.
  const startAt = last.w > 0.5 ? last.y : first ? time : time - FADE_WAIT - FADE_IN - 1
  return vec4(1 - smoothstep(startAt + FADE_WAIT, startAt + FADE_WAIT + FADE_IN, time), startAt, 0, 1)
})
// The picture or a shape over it, as far as the scene has risen: until then the still shows through.
function fadingIn(c: vec4): vec4 {
  return vec4(c * (1 - fadeClock.at(vec2(0, 0)).x))
}

function viewColor(p: Pixel) {
  const s = scaleOf()
  const vb = vbOf(p.point, s, originOf(s))
  const u = p.px / s
  const cell = floor(vec2(vb / CELL))
  const local = vec2(vb - cell * CELL)
  const g = ground.at(cell)
  const tag = floor(g.g * 255 + 0.5)
  let acc = vec4(0)

  // Where an animal rests in the still: the bare water again, opaque.
  if (g.a > 0.5) {
    acc = restAt(vb)
  }

  // The glint field: dots on a 15-unit pattern in four breathing ellipses, all drifting; under the island's and
  // shoal's tiles, which hide them by their own opacity. The ellipses lie in the four quarters, one in each.
  const drift = motion.at(vec2(2, 0))
  const breathe = motion.at(vec2(3, 0))
  const q = vec2(vb - drift.xy)
  const east = q.x > 800
  const low = east ? q.y > 555 : q.y > 470
  const ellipse = east ? (low ? vec4(1330, 800, 200, 130) : vec4(1400, 330, 170, 110)) : low ? vec4(230, 800, 200, 90) : vec4(180, 150, 170, 80)
  const level = east ? (low ? breathe.z : breathe.x) : low ? breathe.w : breathe.y
  const field = glintOf(q, ellipse.x, ellipse.y, ellipse.z, ellipse.w) * level
  const m = vec2(mod(q, CELL))
  const dot = length(vec2(max(abs(m.x - 7.5) - 1.5, 0), m.y - 7.5)) - 1
  const fill = box2(local, 1, 14, u)
  const hidden = g.r * (fill + 0.24 * (box2(local, 0.5, 14.5, u) - fill))
  const glint = 0.75 * clamp(0.5 - dot / u, 0, 1) * field * (1 - hidden)
  acc = over(vec4(GLINT * glint, glint), acc)

  // A sand tile dimming under its pale veil.
  const veil = tag > 0.5 && tag < 63.5 ? motion.at(vec2(12 + tag, 0)).x * fill : 0
  acc = over(vec4(DIM * veil, veil), acc)

  const homes = motion.at(vec2(0, 0))
  acc = over(poseAt(4, vec2(vb - homes.zw)), acc)

  const honu = vec2(vb - homes.xy)
  const turn = motion.at(vec2(1, 0))
  const shown = vec4(poseAt(turn.x, honu) * turn.y)
  const before = vec4(poseAt(turn.z, honu) * turn.w)
  // The poses stack in order, so the fourth lies over the first as the first fades in.
  acc = over(turn.x < 0.5 ? over(before, shown) : over(shown, before), acc)

  // The sparkle near this cell, if any: a white dot.
  const sp = SPARKS.at(clamp(tag - 64, 0, 8))
  const spark = tag > 63.5 ? motion.at(vec2(tag - 60, 0)).x * clamp((sp.z / 10 - length(vec2(vb - sp.xy))) / u + 0.5, 0, 1) : 0
  acc = over(vec4(vec3(spark), spark), acc)
  return vec4(acc * (params.variant * 0 + 1))
}
const view = picture(p => fadingIn(viewColor(p)))

export default shader({ fps: 30, passes: [fadeClock, motion, cells, atlas, ground, poses, rest, view] })
